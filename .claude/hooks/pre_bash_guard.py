"""
PreToolUse hook for Bash: branch policy, attribution and paid calls.

- `tools/ai/check_ask_context.py` without `--dry-run` calls a real LLM and
  costs money; only the user launches it.
- Never push to `main`, which only changes when the release branch is
  merged into it, in any environment, also through `HEAD`, `@` or `--all`;
  never delete `main` or a release branch (`X.Y.x`).
- A push to a release branch goes through when it carries notes, docs,
  harness or synced assets, the usual direct pushes; when its commits
  change what ships or is tested (`skforecast_ai/`, `tests/`, `packages/`,
  `pyproject.toml`), which normally goes through a pull request, the user
  confirms it.
- Never force push, in any form (`-f`, `--force`, `--force-with-lease`, a
  `+` refspec, `--mirror`); the deny rules in `settings.json` only catch the
  command prefixes they list.
- Commits and pull requests are authored by the user alone: no
  `Co-Authored-By` trailer naming Claude or Anthropic, no `Claude-Session`
  trailer, no "Generated with Claude Code" or "Generated by Claude Code"
  line and no session link, in the command text (`-m`, heredoc) or in a
  message file (`git commit -F`, `gh pr create --body-file`). The
  `attribution` setting in `settings.json` already turns them off; this
  catches messages written by hand. `pre_pr_guard.py` applies the same
  pattern to the pull requests written with the GitHub MCP tools.
- In Claude Code on the web (`CLAUDE_CODE_REMOTE=true`), commits and pushes
  only happen on a branch named `feature/...`, `fix/...`, `docs/...`,
  `chore/...` or `perf/...`, or on the release branch.
- The branches that Claude Code names itself never reach GitHub, in any
  environment: `claude/...` (cloud sessions) and `worktree-...`
  (`claude --worktree`), as the destination of a `git push` (deleting one is
  allowed) or the head of `gh pr create`. A pull request keeps the name of
  its branch, so the branch is renamed to `<type>/<slug>` before the push.
- Merging a pull request asks the user, also through `gh api` (the REST
  merge endpoint or the `mergePullRequest` GraphQL mutation), which the
  `Bash(gh pr merge *)` ask rule in `settings.json` does not match.

Exit code 2 blocks the command and sends the reason back to Claude; a
merge or a push of package code to a release branch prints an `ask`
decision instead, which asks in any permission mode. Confirming every
local push is the `ask` rule in `.claude/settings.local.json`, not here.
"""

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

PROTECTED_BRANCH = re.compile(r"^(main|master|\d+\.\d+\.x)$")
MAIN_BRANCH = re.compile(r"^(main|master)$")
RELEASE_BRANCH = re.compile(r"^\d+\.\d+\.x$")
ALLOWED_BRANCH = re.compile(r"^(feature|fix|docs|chore|perf)/[A-Za-z0-9._/-]+$")
# What ships or is tested: pushing it to a release branch asks first.
PACKAGE_PATHS = ("skforecast_ai/", "tests/", "packages/", "pyproject.toml")
# Branch names generated by Claude Code (cloud sessions, `claude --worktree`).
SESSION_BRANCH = re.compile(r"^(claude/|worktree-)")
RELEASE_REF = re.compile(
    r"refs/(?:heads|remotes/origin)/(\d+)\.(\d+)\.x$", re.MULTILINE
)
GIT_TIMEOUT = 15
SEGMENT_SEPARATOR = re.compile(r"\n|&&|\|\||;|\|")
ENV_ASSIGNMENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
# A redirection (`2>&1`, `>log`, `> log`), which is not an argument; group 1 is
# empty when the target is the next word.
REDIRECTION = re.compile(r"^(?:\d+|&)?(?:>>?|<<?|>&|<&)(.*)$")
# `<<EOF`, `<<-EOF`, `<<'EOF'` or `<<"EOF"`, not a here-string (`<<<word`);
# the group is the delimiter.
HEREDOC_START = re.compile(
    r"(?<!<)<<(?!<)-?\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?"
)
# git options that take a separate value before the subcommand.
GIT_OPTIONS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
# `git push` options that take a separate value.
PUSH_OPTIONS_WITH_VALUE = {"-o", "--push-option", "--repo", "--receive-pack", "--exec"}
FORCE_OPTIONS = ("--force", "--force-with-lease", "--force-if-includes")
# Push every local branch (or mirror the repository), protected ones included.
ALL_BRANCH_OPTIONS = {"--all", "--branches", "--mirror"}
AI_ATTRIBUTION = re.compile(
    r"co-authored-by:[^\n]*(claude|anthropic)"
    r"|generated (?:with|by) \[?claude code"
    r"|claude\.ai/code/session_|^claude-session:",
    re.IGNORECASE | re.MULTILINE,
)
# A `git commit` at the start of a command, found on the raw text because
# `shlex` cannot parse a first line such as `git commit -m "$(cat <<'EOF'`.
COMMIT_COMMAND = re.compile(
    r"(?:^|[;&|(])\s*(?:[A-Za-z_]\w*=\S*\s+)*git(?:\s+-\S+(?:\s+[^-\s]\S*)?)*"
    r"\s+commit(?![\w-])",
    re.MULTILINE,
)
# A `gh pr create` or `gh pr edit` at the start of a command, found on the
# raw text for the same reason: a quoted body that spans several lines.
PR_COMMAND = re.compile(
    r"(?:^|[;&|(])\s*(?:[A-Za-z_]\w*=\S*\s+)*gh\s+pr\s+(?:create|edit)(?![\w-])",
    re.MULTILINE,
)
# Options that read a commit message or a PR body from a file.
MESSAGE_FILE_OPTIONS = ("-F", "--file", "--body-file")
# A pull request merge through `gh api`: REST endpoint or GraphQL mutation.
MERGE_API = re.compile(r"/pulls/\d+/merge\b|mergePullRequest")


def without_heredocs(command: str) -> str:
    """
    Remove the body of every heredoc from `command`: its lines are data
    (a commit message, a file written with `cat`), not commands, so a line
    that reads as one (`python tools/ai/check_ask_context.py` in a README)
    must not be checked as if it ran.
    """

    lines = command.split("\n")
    kept = []
    delimiter = None
    for line in lines:
        if delimiter is not None:
            if line.strip() == delimiter:
                delimiter = None
            continue
        kept.append(line)
        match = HEREDOC_START.search(line)
        if match:
            delimiter = match.group(1)
    return "\n".join(kept)


def segments(command: str) -> list[list[str]]:
    """
    Split `command` into simple commands and return the words of each, with
    leading env assignments and redirections removed. Heredoc bodies are
    left out, and a segment that is not valid shell is skipped.
    """

    result = []
    for segment in SEGMENT_SEPARATOR.split(without_heredocs(command)):
        try:
            words = shlex.split(segment.strip().lstrip("({ "))
        except ValueError:
            continue
        while words and ENV_ASSIGNMENT.match(words[0]):
            words.pop(0)
        arguments = []
        target = False
        for word in words:
            if target:
                target = False
            elif match := REDIRECTION.match(word):
                target = match.group(1) == ""
            else:
                arguments.append(word)
        if arguments:
            result.append(arguments)
    return result


def git_invocations(command: str) -> list[tuple[str, list[str]]]:
    """
    Return `(subcommand, args)` for every segment of `command` whose program
    is git. Only the first word of a segment counts, so `git push` quoted
    inside a heredoc or a grep pattern is ignored.
    """

    invocations = []
    for words in segments(command):
        if os.path.basename(words[0]) != "git":
            continue
        i = 1
        while i < len(words) and words[i].startswith("-"):
            i += 2 if words[i] in GIT_OPTIONS_WITH_VALUE else 1
        if i < len(words):
            invocations.append((words[i], words[i + 1:]))
    return invocations


def push_refspecs(args: list[str]) -> list[str]:
    """
    Refspecs of `git push <args>`: the positional arguments after the
    remote, skipping the values of options such as `-o ci.skip`. With
    `--repo` the remote is an option, so every positional is a refspec.
    """

    positional = []
    i = 0
    while i < len(args):
        if args[i] in PUSH_OPTIONS_WITH_VALUE:
            i += 2
            continue
        if not args[i].startswith("-"):
            positional.append(args[i])
        i += 1
    has_repo = any(a == "--repo" or a.startswith("--repo=") for a in args)
    return positional if has_repo else positional[1:]


def push_pairs(args: list[str], branch: str) -> list[tuple[str, str]]:
    """
    `(source, destination)` of every branch a `git push` writes to. In
    `src:dst` the destination is `dst`, `HEAD` or `@` stand for the current
    branch, and no refspec means the current branch. A deletion (`:dst`,
    `--delete`, `-d`) has an empty source.
    """

    refspecs = push_refspecs(args)
    if not refspecs:
        return [("HEAD", branch)]
    deleting = "--delete" in args or "-d" in args
    pairs = []
    for refspec in refspecs:
        src, colon, dst = refspec.lstrip("+").partition(":")
        if deleting:
            src, dst, colon = "", src, ":"
        dst = (dst if colon else src).removeprefix("refs/heads/")
        if dst in ("", "HEAD", "@"):
            dst = branch
        pairs.append(("HEAD" if src in ("HEAD", "@") else src, dst))
    return pairs


def pushed_files(cwd: str, source: str, branch: str) -> list[str] | None:
    """
    Files changed by the commits that pushing `source` to `branch` sends,
    or None when `origin/<branch>` is not known locally.
    """

    known = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"refs/remotes/origin/{branch}"],
        cwd=cwd, capture_output=True, text=True,
    )
    if known.returncode != 0:
        return None
    names = subprocess.run(
        ["git", "log", "--name-only", "--format=", f"origin/{branch}..{source}"],
        cwd=cwd, capture_output=True, text=True,
    )
    return names.stdout.split()


def package_ask(branch: str, paths: list[str] | None) -> str | None:
    """
    The reason to confirm a write to the release branch `branch` that
    changes package code (`paths` None: the changes could not be listed).
    """

    if paths is None:
        return (
            f"This pushes to the release branch '{branch}', but origin/{branch} "
            f"is not fetched, so its commits could not be checked for package "
            f"code (which normally goes through a pull request)."
        )
    files = sorted({p for p in paths if p.startswith(PACKAGE_PATHS)})
    if not files:
        return None
    shown = ", ".join(files[:3]) + (", ..." if len(files) > 3 else "")
    return (
        f"This writes package code to the release branch '{branch}' without "
        f"a pull request ({shown}). Package changes normally go through a "
        f"`<type>/<slug>` branch and a pull request (verify, release note link)."
    )


def pr_head(args: list[str], branch: str) -> str:
    """Head branch of `gh pr create <args>`: `--head`, or the current one."""

    for i, arg in enumerate(args):
        if arg in ("--head", "-H") and i + 1 < len(args):
            head = args[i + 1]
        elif arg.startswith("--head="):
            head = arg.split("=", 1)[1]
        else:
            continue
        return head.split(":", 1)[-1]  # `owner:branch`
    return branch


def release_branch(cwd: str) -> str | None:
    """
    The release branch in development: the `X.Y.x` branch of `origin` with
    the highest version (from GitHub, or else from the local refs), or None.
    Not `__version__`, which on `main` is still the previous release.
    """

    refs = []
    for args in (
        ["ls-remote", "--heads", "origin", "refs/heads/*.x"],
        ["for-each-ref", "--format=%(refname)", "refs/remotes/origin/"],
    ):
        try:
            result = subprocess.run(
                ["git", *args], cwd=cwd, capture_output=True, text=True,
                timeout=GIT_TIMEOUT,
                env={**os.environ, "GIT_TERMINAL_PROMPT": "0"},
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        refs = [m.groups() for m in RELEASE_REF.finditer(result.stdout)]
        if refs:
            break
    if not refs:
        return None
    major, minor = max((int(a), int(b)) for a, b in refs)
    return f"{major}.{minor}.x"


def session_branch_message(branch: str, cwd: str, mcp: bool = False) -> str:
    """
    How to move the work of `branch` to a `<type>/<slug>` branch: rename
    the local branch, or with the GitHub MCP tools (which may have no local
    branch) use another name.
    """

    release = release_branch(cwd) or "X.Y.x"
    if mcp:
        return (
            f"Blocked: '{branch}' is a branch name generated by Claude Code, "
            f"and a pull request keeps the name of its branch. Use a "
            f"`<type>/<slug>` name (type feature, fix, docs, chore or perf), "
            f"created from `origin/{release}`, instead."
        )
    return (
        f"Blocked: '{branch}' is a branch name generated by Claude Code, and a "
        f"pull request keeps the name of its branch. Rename it with "
        f"`git branch -m <type>/<slug>` (type feature, fix, docs, chore or "
        f"perf), "
        f"check that `git log --oneline origin/{release}..HEAD` lists only "
        f"the commits of this work (if the branch started from `main`, move "
        f"them with `git rebase --onto origin/{release} origin/main`), and "
        f"push that branch instead."
    )


def forces(args: list[str]) -> bool:
    """
    Whether a `git push` rewrites remote history: a force option, `-f` in a
    cluster of short options (`-uf`), or a refspec starting with `+`.
    """

    for arg in args:
        if arg.startswith(FORCE_OPTIONS):
            return True
        if arg.startswith("-") and not arg.startswith("--") and "f" in arg[1:]:
            return True
    return any(refspec.startswith("+") for refspec in push_refspecs(args))


def message_files(args: list[str]) -> list[str]:
    """
    Paths given to `-F`, `--file` or `--body-file`, in the forms `-F path`,
    `-Fpath` and `--file=path`. `-` (stdin) is skipped.
    """

    paths = []
    for i, arg in enumerate(args):
        for option in MESSAGE_FILE_OPTIONS:
            if arg == option and i + 1 < len(args):
                paths.append(args[i + 1])
            elif arg.startswith(option + "="):
                paths.append(arg.split("=", 1)[1])
            elif option == "-F" and arg.startswith("-F") and len(arg) > 2:
                paths.append(arg[2:])
    return [p for p in paths if p != "-"]


def writes_message(words: list[str]) -> bool:
    """Whether a simple command writes a commit message or a PR body."""

    program = os.path.basename(words[0])
    if program == "gh":
        return words[1:2] == ["pr"] and words[2:3] in (["create"], ["edit"])
    return False


def merges_pr(words: list[str]) -> bool:
    """Whether a simple command merges a pull request."""

    if os.path.basename(words[0]) != "gh":
        return False
    if words[1:3] == ["pr", "merge"]:
        return True
    return words[1:2] == ["api"] and any(MERGE_API.search(w) for w in words[2:])


def ask(reasons: list[str]) -> int:
    """
    Print an `ask` decision with `reasons`, if any, so the user confirms the
    call in any permission mode, and return the exit code.
    """

    if reasons:
        print(json.dumps({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "ask",
                "permissionDecisionReason": " ".join(dict.fromkeys(reasons)),
            }
        }))
    return 0


def merge_asks(command: str) -> list[str]:
    """The reason to confirm `command` when it merges a pull request."""

    if any(merges_pr(words) for words in segments(command)):
        return ["Merging a pull request needs the user's confirmation."]
    return []


def has_ai_attribution(command: str, cwd: str) -> bool:
    """
    Whether a command that writes a commit message or a PR body carries an
    AI attribution line, in its own text (which includes any heredoc) or in
    the message files it reads.
    """

    writers = [
        args for sub, args in git_invocations(command) if sub == "commit"
    ] + [words[3:] for words in segments(command) if writes_message(words)]
    raw_writer = COMMIT_COMMAND.search(command) or PR_COMMAND.search(command)
    if not writers and not raw_writer:
        return False
    if AI_ATTRIBUTION.search(command):
        return True
    for args in writers:
        for path in message_files(args):
            try:
                text = (Path(cwd) / path).read_text(errors="ignore")
            except OSError:
                continue
            if AI_ATTRIBUTION.search(text):
                return True
    return False


def current_branch(cwd: str) -> str:
    """Return the checked out branch, or an empty string when detached."""

    result = subprocess.run(
        ["git", "rev-parse", "--abbrev-ref", "HEAD"],
        cwd=cwd,
        capture_output=True,
        text=True,
    )
    branch = result.stdout.strip()
    return "" if branch == "HEAD" else branch


def main() -> int:
    payload = json.load(sys.stdin)
    command = payload.get("tool_input", {}).get("command", "")

    for words in segments(command):
        runs_check = os.path.basename(words[0]).startswith("python") and any(
            w.endswith("check_ask_context.py") for w in words[1:2]
        )
        if runs_check and "--dry-run" not in words:
            print(
                "Blocked: check_ask_context.py without --dry-run calls a real "
                "LLM and costs money. Run it with --dry-run, or ask the user "
                "to launch the real run.",
                file=sys.stderr,
            )
            return 2

    cwd = os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or "."
    if has_ai_attribution(command, cwd):
        print(
            "Blocked: commits and pull requests are authored by the user "
            "alone (AGENTS.md). Remove the Co-Authored-By trailer naming "
            "Claude or Anthropic, the Claude-Session trailer, any "
            "'Generated with Claude Code' or 'Generated by Claude Code' "
            "line and the session link.",
            file=sys.stderr,
        )
        return 2

    pr_heads = [
        pr_head(words[3:], current_branch(cwd))
        for words in segments(command)
        if os.path.basename(words[0]) == "gh" and words[1:3] == ["pr", "create"]
    ]
    for head in pr_heads:
        if SESSION_BRANCH.match(head):
            print(session_branch_message(head, cwd), file=sys.stderr)
            return 2

    invocations = [
        (sub, args)
        for sub, args in git_invocations(command)
        if sub in {"commit", "push"}
    ]
    if COMMIT_COMMAND.search(command) and not any(
        sub == "commit" for sub, _ in invocations
    ):
        invocations.append(("commit", []))
    if not invocations:
        return ask(merge_asks(command))

    branch = current_branch(cwd)
    remote = os.environ.get("CLAUDE_CODE_REMOTE", "").lower() == "true"
    asks = []

    for sub, args in invocations:
        if sub != "push":
            continue
        if forces(args):
            release = release_branch(cwd) or "X.Y.x"
            print(
                "Blocked: force pushes rewrite published history and are not "
                "allowed (AGENTS.md). Push new commits on top instead; merge "
                "the base branch rather than rebasing a pushed branch. If the "
                "pull request of this branch is already merged, push the "
                "follow-up to a new <type>/<slug> branch created from "
                f"origin/{release} instead.",
                file=sys.stderr,
            )
            return 2
        if ALL_BRANCH_OPTIONS.intersection(args):
            print(
                "Blocked: --all, --branches and --mirror push every local "
                "branch, protected ones included. Push the current branch: "
                f"`git push -u origin {branch or '<branch>'}`.",
                file=sys.stderr,
            )
            return 2
        for source, target in push_pairs(args, branch):
            if not source:
                # Deleting a session branch cleans it up.
                if PROTECTED_BRANCH.match(target):
                    print(
                        f"Blocked: deleting {target} is not allowed.",
                        file=sys.stderr,
                    )
                    return 2
                continue
            if MAIN_BRANCH.match(target):
                print(
                    f"Blocked: {target} only changes when the release branch "
                    f"is merged into it at release time. Push a "
                    f"<type>/<slug> branch and open the pull request against "
                    f"the release branch.",
                    file=sys.stderr,
                )
                return 2
            if SESSION_BRANCH.match(target):
                print(session_branch_message(target, cwd), file=sys.stderr)
                return 2
            if RELEASE_BRANCH.match(target):
                reason = package_ask(target, pushed_files(cwd, source, target))
                asks += [reason] if reason else []

    allowed = ALLOWED_BRANCH.match(branch) or RELEASE_BRANCH.match(branch)
    if remote and not allowed:
        print(
            f"Blocked: current branch '{branch}' does not follow the naming "
            f"convention. Before committing or pushing, create a branch named "
            f"<type>/<short-slug> with type feature, fix, docs, chore or perf, "
            f"for example `git checkout -b fix/lag-validation`, or rename this "
            f"one with `git branch -m fix/lag-validation` to keep its commits.",
            file=sys.stderr,
        )
        return 2

    return ask(asks + merge_asks(command))


if __name__ == "__main__":
    sys.exit(main())
