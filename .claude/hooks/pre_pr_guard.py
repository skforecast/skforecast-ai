"""
PreToolUse hook for the GitHub MCP tools that write a pull request
(`create_pull_request`, `update_pull_request`) or a branch (`create_branch`,
`push_files`, `create_or_update_file`, `delete_file`): attribution and
branch policy.

A cloud session opens its pull requests with these tools, not with `gh`, so
the Bash guard never sees their title and body; this blocks an attribution
line written by Claude, with the same pattern the Bash guard applies to
commit messages and `gh pr create`, also in the commit message of the tools
that commit. The "Generated by [Claude Code](session link)" footer of a
cloud session is not written by Claude but appended by the GitHub MCP server
after this check; `post_pr_footer.py` has it removed.

The tools that commit write to GitHub directly, past the Bash guard, so the
same branch rules apply to their `branch` (and to the `head` of a new pull
request): never `main`, never a branch named by Claude Code (`claude/...`,
`worktree-...`), the user confirms package files written to a release
branch (`X.Y.x`), and in a cloud session only `<type>/<slug>` or the
release branch.

Exit code 2 blocks the call and sends the reason back to Claude; package
files on a release branch print an `ask` decision instead.
"""

import json
import os
import re
import sys

from pre_bash_guard import (
    AI_ATTRIBUTION,
    ALLOWED_BRANCH,
    MAIN_BRANCH,
    RELEASE_BRANCH,
    SESSION_BRANCH,
    ask,
    package_ask,
    session_branch_message,
)

CHECKED_FIELDS = ("title", "body", "message")
# Tools that create a branch or commit to one, through their `branch` field.
BRANCH_TOOL = re.compile(
    r"__(create_branch|push_files|create_or_update_file|delete_file)$"
)


def branch_error(tool_name: str, tool_input: dict, cwd: str) -> str | None:
    """Why the branch of a GitHub MCP write call breaks the policy, if it does."""

    remote = os.environ.get("CLAUDE_CODE_REMOTE", "").lower() == "true"
    branch = head = ""
    if BRANCH_TOOL.search(tool_name):
        branch = str(tool_input.get("branch") or "")
    if tool_name.endswith("__create_pull_request"):
        head = str(tool_input.get("head") or "").split(":", 1)[-1]
    for name in (branch, head):
        if SESSION_BRANCH.match(name):
            return session_branch_message(name, cwd, mcp=True)
    if MAIN_BRANCH.match(branch):
        return (
            f"Blocked: {branch} only changes when the release branch is "
            f"merged into it at release time. Commit to a <type>/<slug> "
            f"branch and open the pull request against the release branch."
        )
    allowed = ALLOWED_BRANCH.match(branch) or RELEASE_BRANCH.match(branch)
    if remote and branch and not allowed:
        return (
            f"Blocked: branch '{branch}' does not follow the naming "
            f"convention. Use a branch named <type>/<short-slug> with type "
            f"feature, fix, docs, chore or perf."
        )
    return None


def written_paths(tool_input: dict) -> list[str]:
    """Paths that a GitHub MCP commit tool writes (`path`, `files[].path`)."""

    files = tool_input.get("files") or []
    paths = [tool_input.get("path")] + [
        f.get("path") for f in files if isinstance(f, dict)
    ]
    return [p for p in paths if isinstance(p, str)]


def main() -> int:
    payload = json.load(sys.stdin)
    tool_name = payload.get("tool_name", "")
    tool_input = payload.get("tool_input", {})
    for field in CHECKED_FIELDS:
        value = tool_input.get(field)
        if isinstance(value, str) and AI_ATTRIBUTION.search(value):
            print(
                f"Blocked: the {field} carries an AI attribution line. "
                "Commits and pull requests are authored by the user alone "
                "(AGENTS.md): remove the 'Generated by Claude Code' footer, "
                "the session link and any Co-Authored-By trailer naming "
                "Claude or Anthropic, then call the tool again.",
                file=sys.stderr,
            )
            return 2

    cwd = os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or "."
    error = branch_error(tool_name, tool_input, cwd)
    if error:
        print(error, file=sys.stderr)
        return 2
    branch = str(tool_input.get("branch") or "")
    if BRANCH_TOOL.search(tool_name) and RELEASE_BRANCH.match(branch):
        reason = package_ask(branch, written_paths(tool_input))
        return ask([reason] if reason else [])
    return 0


if __name__ == "__main__":
    sys.exit(main())
