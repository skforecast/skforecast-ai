"""
PreToolUse hook for the GitHub MCP tools that write a pull request
(`create_pull_request`, `update_pull_request`): attribution.

A cloud session opens its pull requests with these tools, not with `gh`, so
the Bash guard never sees their title and body; this blocks an attribution
line written by Claude, with the same pattern the Bash guard applies to
commit messages and `gh pr create`. The "Generated by [Claude Code](session
link)" footer of a cloud session is not written by Claude but appended by
the GitHub MCP server after this check; `post_pr_footer.py` has it removed.

Exit code 2 blocks the call and sends the reason back to Claude.
"""

import json
import sys

from pre_bash_guard import AI_ATTRIBUTION

CHECKED_FIELDS = ("title", "body")


def main() -> int:
    payload = json.load(sys.stdin)
    tool_input = payload.get("tool_input", {})
    for field in CHECKED_FIELDS:
        value = tool_input.get(field)
        if isinstance(value, str) and AI_ATTRIBUTION.search(value):
            print(
                f"Blocked: the pull request {field} carries an AI attribution "
                "line. Pull requests are authored by the user alone "
                "(AGENTS.md): remove the 'Generated by Claude Code' footer, "
                "the session link and any Co-Authored-By trailer naming "
                "Claude or Anthropic, then call the tool again.",
                file=sys.stderr,
            )
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
